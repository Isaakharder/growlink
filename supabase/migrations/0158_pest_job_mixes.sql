-- Pest Control execution: actual mixes, leftovers and an audit history.
--
-- Until now a spray job's mixes lived only inside
-- pest_control_todos.progress_snapshot.mixes, were capped at the planned tank
-- count, and always recorded the planned water/chemical amounts. This
-- migration gives each mix its own row with what the operator actually put in
-- the tank, how much was left over, and every later correction.
--
--   pest_job_mixes           one row per mix actually made (planned or extra)
--   pest_job_mix_revisions   append-only history: created / corrected /
--                            leftover / closed / imported
--   pest_control_records     + mix_summary (planned vs actual, frozen at
--                            completion) and a UNIQUE (todo_id) so a retried
--                            completion can never write a second record
--
-- The plan itself (pest_control_todos.calculation_snapshot) is never changed:
-- it stays the baseline the actual figures are compared against.
--
-- Functions (called by the Express server with the service-role key):
--   pest_mix_save(org, todo, user, mix)     create or correct one mix
--   pest_job_mixes_load(org, todo)          mixes + history (imports legacy
--                                           snapshot mixes on first read)
--   pest_job_complete(org, todo, user, …)   record + status + inventory in
--                                           one transaction, idempotent
--
-- Only adds tables, columns, a constraint and functions; one transaction.

begin;

-- ── Mixes ────────────────────────────────────────────────────────────────────

create table if not exists public.pest_job_mixes (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references public.organizations(id),
  todo_id uuid not null references public.pest_control_todos(id) on delete cascade,
  -- Generated by the device that started the mix. A retried or replayed
  -- (offline queue) request carries the same key, so it can never add a
  -- second mix.
  client_key uuid not null,
  mix_number integer not null check (mix_number >= 1),
  status text not null default 'active' check (status in ('active', 'completed')),
  -- true when the mix number is beyond the plan's tank count at the time
  -- it was made (an extra mix). Informational only — never a limit.
  is_extra boolean not null default false,
  -- What the plan said this mix should contain (prefill baseline).
  planned_water_l numeric check (planned_water_l is null or planned_water_l >= 0),
  planned_chemicals jsonb not null default '[]',
  -- What the operator actually put in the tank.
  water_l numeric not null check (water_l >= 0),
  -- [{ chemical_id, name, amount, unit }] — unit is the plan's base unit
  -- (ml for liquids, g for dry products).
  chemicals jsonb not null default '[]',
  -- Mixture not applied to the crop (drained, returned, left in the tank).
  leftover_l numeric not null default 0 check (leftover_l >= 0),
  started_at timestamptz not null default now(),
  ended_at timestamptz,
  revision integer not null default 1,
  created_by uuid,
  updated_by uuid,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint pest_job_mixes_leftover_within_water check (leftover_l <= water_l),
  constraint pest_job_mixes_todo_client_key_key unique (todo_id, client_key),
  constraint pest_job_mixes_todo_mix_number_key unique (todo_id, mix_number)
);

create index if not exists pest_job_mixes_organization_id_idx on public.pest_job_mixes (organization_id);

alter table public.pest_job_mixes enable row level security;

create policy pest_job_mixes_select_org on public.pest_job_mixes
  for select to authenticated using (public.is_org_member(organization_id));

grant select, insert, update, delete on table public.pest_job_mixes to service_role;
grant select on table public.pest_job_mixes to authenticated;

-- ── History (append-only) ────────────────────────────────────────────────────

create table if not exists public.pest_job_mix_revisions (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references public.organizations(id),
  todo_id uuid not null references public.pest_control_todos(id) on delete cascade,
  mix_id uuid not null references public.pest_job_mixes(id) on delete cascade,
  revision integer not null,
  action text not null check (action in ('created', 'corrected', 'leftover', 'closed', 'imported')),
  before jsonb,
  after jsonb not null,
  reason text,
  changed_by uuid,
  changed_at timestamptz not null default now(),
  constraint pest_job_mix_revisions_mix_revision_key unique (mix_id, revision)
);

create index if not exists pest_job_mix_revisions_todo_idx on public.pest_job_mix_revisions (organization_id, todo_id);

alter table public.pest_job_mix_revisions enable row level security;

create policy pest_job_mix_revisions_select_org on public.pest_job_mix_revisions
  for select to authenticated using (public.is_org_member(organization_id));

grant select, insert, update, delete on table public.pest_job_mix_revisions to service_role;
grant select on table public.pest_job_mix_revisions to authenticated;

-- ── Records ──────────────────────────────────────────────────────────────────

alter table public.pest_control_records
  add column if not exists mix_summary jsonb;

-- One record per job. Fails (and rolls this migration back) if duplicates
-- already exist, rather than silently keeping them.
do $$
begin
  if not exists (
    select 1 from pg_constraint where conname = 'pest_control_records_todo_id_key'
  ) then
    alter table public.pest_control_records
      add constraint pest_control_records_todo_id_key unique (todo_id);
  end if;
end $$;

-- ── Helpers ──────────────────────────────────────────────────────────────────

create or replace function public.pest_mix_json(m public.pest_job_mixes)
returns jsonb
language sql
stable
as $$
  select jsonb_build_object(
    'id', m.id, 'client_key', m.client_key, 'mix_number', m.mix_number,
    'status', m.status, 'is_extra', m.is_extra,
    'planned_water_l', m.planned_water_l, 'planned_chemicals', m.planned_chemicals,
    'water_l', m.water_l, 'chemicals', m.chemicals, 'leftover_l', m.leftover_l,
    'started_at', m.started_at, 'ended_at', m.ended_at, 'revision', m.revision,
    'created_by', m.created_by, 'updated_by', m.updated_by, 'updated_at', m.updated_at
  );
$$;

-- Normalises and checks a chemicals array: every line must be the job's own
-- planned chemical (the chemical checks made when the plan was saved are not
-- bypassed by recording a mix), with a non-negative amount.
create or replace function public.pest_mix_chemicals(p_lines jsonb, p_planned_chemical uuid)
returns jsonb
language plpgsql
stable
as $$
declare
  v_line jsonb;
  v_out jsonb := '[]'::jsonb;
  v_amount numeric;
begin
  if p_lines is null or jsonb_typeof(p_lines) <> 'array' then
    raise exception 'chemicals must be an array' using errcode = 'GL422';
  end if;
  for v_line in select * from jsonb_array_elements(p_lines) loop
    if p_planned_chemical is null or (v_line->>'chemical_id') is distinct from p_planned_chemical::text then
      raise exception 'Only the job''s planned chemical can be recorded in a mix' using errcode = 'GL422';
    end if;
    if jsonb_typeof(v_line->'amount') <> 'number' then
      raise exception 'Chemical amount must be a number' using errcode = 'GL422';
    end if;
    v_amount := (v_line->>'amount')::numeric;
    if v_amount < 0 then
      raise exception 'Chemical amount must be 0 or greater' using errcode = 'GL422';
    end if;
    if coalesce(v_line->>'unit', '') not in ('ml', 'g') then
      raise exception 'Chemical unit must be ml or g' using errcode = 'GL422';
    end if;
    v_out := v_out || jsonb_build_array(jsonb_build_object(
      'chemical_id', v_line->>'chemical_id',
      'name', coalesce(v_line->>'name', ''),
      'amount', v_amount,
      'unit', v_line->>'unit'
    ));
  end loop;
  if exists (
    select 1 from jsonb_array_elements(v_out) e group by e->>'chemical_id' having count(*) > 1
  ) then
    raise exception 'Each chemical can only appear once per mix' using errcode = 'GL422';
  end if;
  return v_out;
end;
$$;

-- ── Load (and import legacy snapshot mixes once) ─────────────────────────────

create or replace function public.pest_job_mixes_load(p_org uuid, p_todo uuid)
returns jsonb
language plpgsql
as $$
declare
  t record;
  v_legacy jsonb;
  v_unit text;
  m public.pest_job_mixes;
begin
  select id, chemical_id, chemical_snapshot, calculation_snapshot, progress_snapshot
    into t
    from public.pest_control_todos
   where id = p_todo and organization_id = p_org;
  if not found then
    raise exception 'Todo not found' using errcode = 'GL404';
  end if;

  -- Jobs started before 0158 kept their mixes in progress_snapshot.mixes
  -- with the planned amounts. Bring them in once so they keep counting.
  v_legacy := t.progress_snapshot->'mixes';
  if jsonb_typeof(v_legacy) = 'array' and jsonb_array_length(v_legacy) > 0
     and not exists (select 1 from public.pest_job_mixes where todo_id = p_todo) then
    v_unit := case when coalesce(t.calculation_snapshot->>'rate_unit', t.chemical_snapshot->>'rate_unit', '') ~ '^(g|kg)_' then 'g' else 'ml' end;
    for m in
      insert into public.pest_job_mixes (
        organization_id, todo_id, client_key, mix_number, status, is_extra,
        planned_water_l, planned_chemicals, water_l, chemicals, leftover_l,
        started_at, ended_at
      )
      select p_org, p_todo,
             md5(p_todo::text || ':legacy-mix:' || (e->>'mixNumber'))::uuid,
             (e->>'mixNumber')::int,
             case when e->>'status' = 'completed' then 'completed' else 'active' end,
             false,
             (e->>'waterVolumeL')::numeric,
             case when t.chemical_id is null then '[]'::jsonb else jsonb_build_array(jsonb_build_object(
               'chemical_id', t.chemical_id, 'name', coalesce(t.chemical_snapshot->>'name', ''),
               'amount', coalesce((e->>'chemicalAmountMl')::numeric, 0), 'unit', v_unit)) end,
             greatest(coalesce((e->>'waterVolumeL')::numeric, 0), 0),
             case when t.chemical_id is null then '[]'::jsonb else jsonb_build_array(jsonb_build_object(
               'chemical_id', t.chemical_id, 'name', coalesce(t.chemical_snapshot->>'name', ''),
               'amount', greatest(coalesce((e->>'chemicalAmountMl')::numeric, 0), 0), 'unit', v_unit)) end,
             0,
             coalesce((e->>'startedAt')::timestamptz, now()),
             (e->>'endedAt')::timestamptz
        from jsonb_array_elements(v_legacy) e
       where jsonb_typeof(e->'mixNumber') = 'number'
      on conflict do nothing
      returning *
    loop
      insert into public.pest_job_mix_revisions (organization_id, todo_id, mix_id, revision, action, before, after, reason)
      values (p_org, p_todo, m.id, 1, 'imported', null, public.pest_mix_json(m), 'Recorded before actual mix amounts were tracked (planned amounts)');
    end loop;
  end if;

  return jsonb_build_object(
    'mixes', coalesce((
      select jsonb_agg(public.pest_mix_json(x) order by x.mix_number)
        from public.pest_job_mixes x
       where x.todo_id = p_todo and x.organization_id = p_org
    ), '[]'::jsonb),
    'revisions', coalesce((
      select jsonb_agg(jsonb_build_object(
               'mix_id', r.mix_id, 'revision', r.revision, 'action', r.action,
               'before', r.before, 'after', r.after, 'reason', r.reason,
               'changed_by', r.changed_by, 'changed_at', r.changed_at
             ) order by r.changed_at, r.revision)
        from public.pest_job_mix_revisions r
       where r.todo_id = p_todo and r.organization_id = p_org
    ), '[]'::jsonb)
  );
end;
$$;

-- ── Save (create or correct one mix) ─────────────────────────────────────────
-- p_mix: { client_key, mix_number, water_l, chemicals, leftover_l?, status?,
--          reason?, previous_leftover_l? }
--   new client_key  → creates mix #mix_number (must be the next number) and
--                     closes the mix that was in use, recording
--                     previous_leftover_l on it when given
--   known client_key, same values → no-op (a retry)
--   known client_key, new values  → correction, one history row

create or replace function public.pest_mix_save(p_org uuid, p_todo uuid, p_user uuid, p_mix jsonb)
returns jsonb
language plpgsql
as $$
declare
  t record;
  m public.pest_job_mixes;
  prev public.pest_job_mixes;
  v_before jsonb;
  v_key uuid;
  v_num integer;
  v_next integer;
  v_planned integer;
  v_water numeric;
  v_leftover numeric;
  v_prev_leftover numeric;
  v_chems jsonb;
  v_status text;
  v_reason text;
  v_action text;
  v_unit text;
  v_is_last boolean;
  v_planned_water numeric;
  v_planned_chem numeric;
begin
  if p_mix is null or jsonb_typeof(p_mix) <> 'object' then
    raise exception 'Invalid mix' using errcode = 'GL422';
  end if;

  select id, status, chemical_id, chemical_snapshot, calculation_snapshot
    into t
    from public.pest_control_todos
   where id = p_todo and organization_id = p_org
   for update;
  if not found then
    raise exception 'Todo not found' using errcode = 'GL404';
  end if;

  begin
    v_key := (p_mix->>'client_key')::uuid;
  exception when others then
    raise exception 'client_key must be a UUID' using errcode = 'GL422';
  end;
  if v_key is null then
    raise exception 'client_key must be a UUID' using errcode = 'GL422';
  end if;

  if jsonb_typeof(p_mix->'water_l') <> 'number' or (p_mix->>'water_l')::numeric < 0 then
    raise exception 'Water must be 0 L or more' using errcode = 'GL422';
  end if;
  v_water := (p_mix->>'water_l')::numeric;
  v_chems := public.pest_mix_chemicals(coalesce(p_mix->'chemicals', '[]'::jsonb), t.chemical_id);
  v_reason := nullif(btrim(coalesce(p_mix->>'reason', '')), '');

  select * into m from public.pest_job_mixes where todo_id = p_todo and client_key = v_key for update;

  if not found then
    -- ── New mix ──────────────────────────────────────────────────────────
    if t.status in ('completed', 'cancelled') then
      raise exception 'This job is already %', t.status using errcode = 'GL409';
    end if;
    if jsonb_typeof(p_mix->'mix_number') <> 'number' then
      raise exception 'mix_number is required' using errcode = 'GL422';
    end if;
    v_num := (p_mix->>'mix_number')::int;
    select coalesce(max(mix_number), 0) + 1 into v_next from public.pest_job_mixes where todo_id = p_todo;
    if v_num <> v_next then
      raise exception 'Mix #% was already recorded for this job (next is #%). Reload the job.', v_num, v_next using errcode = 'GL409';
    end if;
    v_leftover := coalesce((p_mix->>'leftover_l')::numeric, 0);
    if v_leftover < 0 or v_leftover > v_water then
      raise exception 'Leftover must be between 0 and the water in the tank' using errcode = 'GL422';
    end if;

    -- Close the mix that was in use. Its leftover is recorded here so a
    -- retry of this whole call cannot record it twice.
    v_prev_leftover := case when jsonb_typeof(p_mix->'previous_leftover_l') = 'number'
                            then (p_mix->>'previous_leftover_l')::numeric end;
    for prev in
      select * from public.pest_job_mixes where todo_id = p_todo and status = 'active' for update
    loop
      if v_prev_leftover is not null and (v_prev_leftover < 0 or v_prev_leftover > prev.water_l) then
        raise exception 'Leftover in mix #% must be between 0 and % L', prev.mix_number, prev.water_l using errcode = 'GL422';
      end if;
      v_before := public.pest_mix_json(prev);
      update public.pest_job_mixes
         set status = 'completed',
             ended_at = now(),
             leftover_l = coalesce(v_prev_leftover, leftover_l),
             revision = revision + 1,
             updated_by = p_user,
             updated_at = now()
       where id = prev.id
       returning * into prev;
      insert into public.pest_job_mix_revisions (organization_id, todo_id, mix_id, revision, action, before, after, reason, changed_by)
      values (p_org, p_todo, prev.id, prev.revision, 'closed', v_before, public.pest_mix_json(prev), null, p_user);
    end loop;

    -- Planned baseline for this mix number (full tank; the plan's final
    -- partial tank for the last planned number; a full tank for extras).
    v_planned := coalesce(nullif(t.calculation_snapshot->>'tank_count', '')::numeric::int, 0);
    v_is_last := v_planned > 0 and v_num = v_planned and coalesce((t.calculation_snapshot->>'is_last_full')::boolean, false) = false;
    v_planned_water := case when v_is_last then coalesce(nullif(t.calculation_snapshot->>'final_tank_volume_l', '')::numeric, nullif(t.calculation_snapshot->>'tank_volume_l', '')::numeric)
                            else nullif(t.calculation_snapshot->>'tank_volume_l', '')::numeric end;
    v_planned_chem := case when v_is_last then coalesce(nullif(t.calculation_snapshot->>'chem_for_final_tank_ml', '')::numeric, nullif(t.calculation_snapshot->>'chem_per_full_tank_ml', '')::numeric)
                           else nullif(t.calculation_snapshot->>'chem_per_full_tank_ml', '')::numeric end;
    v_unit := case when coalesce(t.calculation_snapshot->>'rate_unit', t.chemical_snapshot->>'rate_unit', '') ~ '^(g|kg)_' then 'g' else 'ml' end;

    insert into public.pest_job_mixes (
      organization_id, todo_id, client_key, mix_number, status, is_extra,
      planned_water_l, planned_chemicals, water_l, chemicals, leftover_l,
      created_by, updated_by
    ) values (
      p_org, p_todo, v_key, v_num,
      case when p_mix->>'status' = 'completed' then 'completed' else 'active' end,
      v_planned > 0 and v_num > v_planned,
      v_planned_water,
      case when t.chemical_id is null or v_planned_chem is null then '[]'::jsonb else jsonb_build_array(jsonb_build_object(
        'chemical_id', t.chemical_id, 'name', coalesce(t.chemical_snapshot->>'name', ''),
        'amount', v_planned_chem, 'unit', v_unit)) end,
      v_water, v_chems, v_leftover,
      p_user, p_user
    )
    returning * into m;
    if m.status = 'completed' then
      update public.pest_job_mixes set ended_at = now() where id = m.id returning * into m;
    end if;

    insert into public.pest_job_mix_revisions (organization_id, todo_id, mix_id, revision, action, before, after, reason, changed_by)
    values (p_org, p_todo, m.id, 1, 'created', null, public.pest_mix_json(m), v_reason, p_user);

    if t.status = 'pending' then
      update public.pest_control_todos set status = 'in_progress', updated_at = now()
       where id = p_todo and organization_id = p_org;
    end if;

    return jsonb_build_object('mix', public.pest_mix_json(m), 'created', true, 'changed', true);
  end if;

  -- ── Existing mix: correction / leftover / close ────────────────────────
  if m.organization_id <> p_org then
    raise exception 'Todo not found' using errcode = 'GL404';
  end if;
  v_leftover := case when p_mix ? 'leftover_l' then (p_mix->>'leftover_l')::numeric else m.leftover_l end;
  if v_leftover < 0 or v_leftover > v_water then
    raise exception 'Leftover must be between 0 and the water in the tank' using errcode = 'GL422';
  end if;
  v_status := coalesce(p_mix->>'status', m.status);
  if v_status not in ('active', 'completed') then
    raise exception 'status must be active or completed' using errcode = 'GL422';
  end if;
  if m.status = 'completed' and v_status = 'active' then
    raise exception 'A finished mix cannot be put back in use; start a new mix instead' using errcode = 'GL409';
  end if;

  if m.water_l = v_water and m.chemicals = v_chems and m.leftover_l = v_leftover and m.status = v_status then
    return jsonb_build_object('mix', public.pest_mix_json(m), 'created', false, 'changed', false);
  end if;

  if m.water_l <> v_water or m.chemicals <> v_chems then
    v_action := 'corrected';
  elsif m.leftover_l <> v_leftover then
    v_action := 'leftover';
  else
    v_action := 'closed';
  end if;

  v_before := public.pest_mix_json(m);
  update public.pest_job_mixes
     set water_l = v_water,
         chemicals = v_chems,
         leftover_l = v_leftover,
         status = v_status,
         ended_at = case when v_status = 'completed' then coalesce(ended_at, now()) else ended_at end,
         revision = revision + 1,
         updated_by = p_user,
         updated_at = now()
   where id = m.id
   returning * into m;

  insert into public.pest_job_mix_revisions (organization_id, todo_id, mix_id, revision, action, before, after, reason, changed_by)
  values (p_org, p_todo, m.id, m.revision, v_action, v_before, public.pest_mix_json(m), v_reason, p_user);

  return jsonb_build_object('mix', public.pest_mix_json(m), 'created', false, 'changed', true);
end;
$$;

-- ── Complete (record + status + inventory, once) ─────────────────────────────
-- p_deductions: [{ chemical_id, qty }] already converted to each chemical's
-- inventory unit by the server (same conversion rules as before 0158).

create or replace function public.pest_job_complete(
  p_org uuid, p_todo uuid, p_user uuid, p_notes text, p_mix_summary jsonb, p_deductions jsonb
)
returns jsonb
language plpgsql
as $$
declare
  t public.pest_control_todos;
  m public.pest_job_mixes;
  v_before jsonb;
  v_record_id uuid;
  v_now timestamptz := now();
  d jsonb;
begin
  select * into t from public.pest_control_todos
   where id = p_todo and organization_id = p_org
   for update;
  if not found then
    raise exception 'Todo not found' using errcode = 'GL404';
  end if;

  select id into v_record_id from public.pest_control_records
   where todo_id = p_todo and organization_id = p_org;
  if found then
    return jsonb_build_object('already_completed', true, 'record_id', v_record_id);
  end if;

  for m in select * from public.pest_job_mixes where todo_id = p_todo and status = 'active' for update loop
    v_before := public.pest_mix_json(m);
    update public.pest_job_mixes
       set status = 'completed', ended_at = v_now, revision = revision + 1, updated_by = p_user, updated_at = v_now
     where id = m.id
     returning * into m;
    insert into public.pest_job_mix_revisions (organization_id, todo_id, mix_id, revision, action, before, after, reason, changed_by)
    values (p_org, p_todo, m.id, m.revision, 'closed', v_before, public.pest_mix_json(m), 'Job completed', p_user);
  end loop;

  insert into public.pest_control_records (
    organization_id, todo_id, type, chemical_id, chemical_snapshot, target_snapshot,
    sprayer_snapshot, tank_snapshot, calculation_snapshot, progress_snapshot,
    completed_by, completed_at, notes, mix_summary
  ) values (
    p_org, p_todo, t.type, t.chemical_id, t.chemical_snapshot, t.target_snapshot,
    t.sprayer_snapshot, t.tank_snapshot, t.calculation_snapshot, t.progress_snapshot,
    p_user, v_now, p_notes, p_mix_summary
  )
  returning id into v_record_id;

  update public.pest_control_todos
     set status = 'completed', completed_by = p_user, completed_at = v_now, updated_at = v_now
   where id = p_todo and organization_id = p_org;

  for d in select * from jsonb_array_elements(coalesce(p_deductions, '[]'::jsonb)) loop
    if jsonb_typeof(d->'qty') = 'number' and (d->>'qty')::numeric > 0 then
      update public.pest_chemicals
         set inventory_qty = greatest(0, coalesce(inventory_qty, 0) - (d->>'qty')::numeric),
             updated_at = v_now
       where id = (d->>'chemical_id')::uuid and organization_id = p_org;
    end if;
  end loop;

  return jsonb_build_object('already_completed', false, 'record_id', v_record_id, 'completed_at', v_now);
